    internal static string VerifyPayload(string question, string answer, IReadOnlyList<ChatCitation> sources) =>
        JsonSerializer.Serialize(new
        {
            question,
            answer,
            passages = sources.Select(source => new { title = source.Title, page = source.Page, quote = source.Snippet })
        });

    internal static bool IsSupported(string json)
    {
        try
        {
            using var document = JsonDocument.Parse(ExtractJson(json));
            return document.RootElement.TryGetProperty("supported", out var supported)
                && supported.ValueKind is JsonValueKind.True or JsonValueKind.False
                && supported.GetBoolean();
        }
        catch (JsonException) { return false; }
    }


    internal static string EvidencePayload(string question, IReadOnlyList<KnowledgeHit> hits, string conversation) =>
        JsonSerializer.Serialize(new
        {
            question,
            conversation,
            passages = hits.Select(hit => new
            {
                chunkId = hit.Id,
                title = hit.Title,
                page = hit.PageNumber,
                segments = ChatEngine.EvidenceSegments(hit.Content).Select((text, segment) => new { segment, text })
            })
        });

    internal static string SummaryPayload(string previousSummary, string transcript) =>
        JsonSerializer.Serialize(new { previousSummary, transcript });

    internal static string ExtractJson(string text)
    {
        var trimmed = (text ?? "").Trim();
        var start = trimmed.IndexOf('{');
        var end = trimmed.LastIndexOf('}');
        return start >= 0 && end > start ? trimmed[start..(end + 1)] : trimmed;
    }
